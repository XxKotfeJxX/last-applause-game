import { readFile, readdir, writeFile } from 'node:fs/promises';
import { join, relative, sep } from 'node:path';

const root=process.cwd(),publicRoot=join(root,'public','assets');
const catalog={};
for(const kind of ['characters','items','environment','ui','audio']){
  let folders=[];try{folders=await readdir(join(publicRoot,kind),{withFileTypes:true});}catch{continue;}
  for(const folder of folders.filter(x=>x.isDirectory())){
    const dir=join(publicRoot,kind,folder.name);let meta;
    try{meta=JSON.parse(await readFile(join(dir,'asset.meta.json'),'utf8'));}catch(e){console.error(`${dir}: asset.meta.json: ${e.message}`);process.exitCode=1;continue;}
    if(catalog[meta.id]){console.error(`${dir}: duplicate visualId ${meta.id}`);process.exitCode=1;continue;}
    const files={};const declared=meta.kind==='character'?Object.fromEntries(Object.entries(meta.clips??{}).map(([k,v])=>[k,v.file])):meta.files??{};
    for(const [slot,file] of Object.entries(declared)){
      if(typeof file!=='string'||file.includes('..')||file.startsWith('/')||file.includes('\\')){console.error(`${dir}: unsafe file ${file}`);process.exitCode=1;continue;}
      try{const entries=await readdir(dir);if(entries.includes(file))files[slot]=relative(join(root,'public'),join(dir,file)).split(sep).join('/');}catch{}
    }
    catalog[meta.id]={kind:meta.kind,base:relative(join(root,'public'),dir).split(sep).join('/')+'/',files,meta};
  }
}
if(!process.exitCode){await writeFile(join(root,'src','generated','catalog.ts'),`// Generated by npm run content:sync. Do not edit.\nexport const assetCatalog = ${JSON.stringify(catalog,null,2)} as Record<string,{kind:string;base:string;files:Record<string,string>;meta:Record<string,unknown>}>;\n`);console.log(`Asset catalog: ${Object.keys(catalog).length} packages.`);}
